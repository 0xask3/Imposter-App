List<WordEntry> _entries(
  String categoryId,
  Difficulty difficulty,
  List<(String, String)> wordsAndHints,
) => [
  for (final (word, hint) in wordsAndHints)
    WordEntry(
      id: '${categoryId}_${_slug(word)}',
      word: word,
      hint: hint,
      categoryIds: {categoryId},
      difficulty: difficulty,
    ),
];

String _slug(String value) => value
    .toLowerCase()
    .replaceAll(RegExp(r'[^a-z0-9]+'), '_')
    .replaceAll(RegExp(r'^_|_$'), '');
